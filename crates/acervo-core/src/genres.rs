fn named(number: &str) -> Option<String> {
    number
        .parse::<usize>()
        .ok()
        .and_then(|n| ID3V1.get(n))
        .map(|name| name.to_string())
}

/// Genre names in one TCON value: "17", "(17)", "(17)Rock", "(RX)" and plain text.
pub fn expand(value: &str) -> Vec<String> {
    if !value.is_empty() && value.bytes().all(|b| b.is_ascii_digit()) {
        return vec![named(value).unwrap_or_else(|| value.to_string())];
    }
    let mut result = Vec::new();
    let mut rest = value;
    while let Some(inner) = rest.strip_prefix('(') {
        if inner.starts_with('(') {
            break; // "((" starts literal text that begins with a parenthesis
        }
        let Some(end) = inner.find(')') else { break };
        let reference = &inner[..end];
        let name = match reference {
            "RX" => Some("Remix".to_string()),
            "CR" => Some("Cover".to_string()),
            digits => named(digits),
        };
        match name {
            Some(name) => result.push(name),
            None => break,
        }
        rest = &inner[end + 1..];
    }
    let text = rest
        .strip_prefix('(')
        .filter(|t| t.starts_with('('))
        .unwrap_or(rest);
    if !text.is_empty() && !result.iter().any(|known| known == text) {
        result.push(text.to_string());
    }
    result
}
